#!/usr/bin/env bash
# Multi-admin deployment user management script.
# Creates system users with home directories and assigns them to webadmins/deployers groups.
#
# Usage:
#   sudo bash setup-deployment-users.sh --init-directories
#   sudo bash setup-deployment-users.sh --user alice --password "pass123" --deployer --pubkey /path/to/alice_id_rsa.pub
#   sudo bash setup-deployment-users.sh --user bob --deployer
#
# Options:
#   --init-directories          Initialize /var/www/carc-app with proper ownership and permissions
#   --user <username>           Create a new system user (can be specified multiple times)
#   --password <password>       Set password for the user (prompted if not provided)
#   --pubkey <path>             Add SSH public key from file
#   --deployer                  Add user to deployers group (can run deployment scripts)
#
# Requires: root (sudo)

set -Eeuo pipefail

APP_DIR="${APP_DIR:-/var/www/carc-app}"
SERVICE_USER="${CARC_SERVICE_USER:-www-data}"
SERVICE_GROUP="${CARC_SERVICE_GROUP:-webadmins}"
DEPLOYER_GROUP="deployers"

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

log_info() {
    echo -e "${GREEN}[INFO]${NC} $*"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $*"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $*" >&2
}

# Check if running as root
if [[ $EUID -ne 0 ]]; then
    log_error "This script must be run as root (use sudo)"
    exit 1
fi

# Initialize groups if they don't exist
ensure_groups() {
    if ! getent group "$SERVICE_GROUP" >/dev/null; then
        log_info "Creating group: $SERVICE_GROUP"
        groupadd "$SERVICE_GROUP"
    fi

    if ! getent group "$DEPLOYER_GROUP" >/dev/null; then
        log_info "Creating group: $DEPLOYER_GROUP"
        groupadd "$DEPLOYER_GROUP"
    fi
}

# Initialize directory structure
init_directories() {
    log_info "Initializing $APP_DIR with proper ownership and permissions"

    if [[ ! -d "$APP_DIR" ]]; then
        log_info "Creating directory: $APP_DIR"
        mkdir -p "$APP_DIR"
    fi

    # Set ownership: www-data:webadmins
    log_info "Setting ownership to $SERVICE_USER:$SERVICE_GROUP"
    chown -R "$SERVICE_USER:$SERVICE_GROUP" "$APP_DIR"

    # Set permissions: 775 on all (webadmins can read/write/execute)
    log_info "Setting permissions to 775"
    chmod -R 775 "$APP_DIR"

    # Enable setgid bit on directories so new files inherit group
    log_info "Enabling setgid bit on directories"
    find "$APP_DIR" -type d -exec chmod g+s {} +

    log_info "Directory initialization complete"
}

# Create a single user
create_user() {
    local username="$1"
    local password="${2:-}"
    local pubkey="${3:-}"
    local is_deployer="${4:-false}"

    if getent passwd "$username" >/dev/null; then
        log_warn "User already exists: $username"
        return 0
    fi

    log_info "Creating user: $username"
    useradd -m -s /bin/bash -G "$SERVICE_GROUP" "$username"

    # Set password if provided
    if [[ -n "$password" ]]; then
        echo "$username:$password" | chpasswd
        log_info "Password set for: $username"
    else
        log_warn "No password provided for $username; use 'passwd $username' to set one"
    fi

    # Add SSH public key if provided
    if [[ -n "$pubkey" && -f "$pubkey" ]]; then
        local ssh_dir="/home/$username/.ssh"
        mkdir -p "$ssh_dir"
        chmod 700 "$ssh_dir"

        cat "$pubkey" >> "$ssh_dir/authorized_keys"
        chmod 600 "$ssh_dir/authorized_keys"
        chown -R "$username:$username" "$ssh_dir"

        log_info "SSH public key added for: $username"
    fi

    # Add to deployers group if requested
    if [[ "$is_deployer" == "true" ]]; then
        usermod -aG "$DEPLOYER_GROUP" "$username"
        log_info "Added $username to deployers group"
    fi

    log_info "User created successfully: $username"
}

# Create sudoers file for deployers
create_sudoers_file() {
    local sudoers_file="/etc/sudoers.d/carc-deployers"
    local app_dir="${APP_DIR}"

    log_info "Creating sudoers file: $sudoers_file"

    cat > "$sudoers_file" << EOF
# Deployers group permissions for CARC application
# Members can restart services and run deployment tasks
# Auto-generated by setup-deployment-users.sh

# Allow deployers to restart the application
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/systemctl restart carc-app@prod
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/systemctl restart carc-app@sandbox
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/systemctl status carc-app@prod
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/systemctl status carc-app@sandbox

# Allow deployers to view service logs
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/journalctl -u carc-app@prod
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/journalctl -u carc-app@sandbox

# Allow deployers to interact with databases
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/sqlite3 /var/carc/prod/data/carc.db
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/sqlite3 /var/carc/sandbox/data/carc.db

# Allow deployers to backup databases
%$DEPLOYER_GROUP ALL=(ALL) NOPASSWD: /usr/bin/bash ${app_dir}/frontend/scripts/backup-sqlite.sh
EOF

    chmod 440 "$sudoers_file"
    log_info "Sudoers file created (mode 440)"

    # Validate the sudoers file
    if visudo -c -f "$sudoers_file" >/dev/null 2>&1; then
        log_info "Sudoers file is valid"
    else
        log_error "Sudoers file validation failed! Check the file manually."
        return 1
    fi
}

# Print usage
print_usage() {
    cat << EOF
Usage: sudo bash $(basename "$0") [OPTIONS]

Options:
  --init-directories          Initialize /var/www/carc-app with proper ownership/permissions
  --user <username>           Create a new system user (repeatable)
  --password <password>       Set password for the user (prompted if not provided)
  --pubkey <path>             Add SSH public key from file
  --deployer                  Add the user to deployers group

Environment Variables:
  APP_DIR                     Application directory (default: /var/www/carc-app)
  CARC_SERVICE_USER          Service user (default: www-data)
  CARC_SERVICE_GROUP         Service group (default: webadmins)

Examples:
  # Initialize directories
  sudo bash setup-deployment-users.sh --init-directories

  # Create a deployer user with password
  sudo bash setup-deployment-users.sh --user alice --password mypass123 --deployer

  # Create a deployer with SSH key
  sudo bash setup-deployment-users.sh --user bob --deployer --pubkey /tmp/bob_key.pub

  # Create multiple users at once
  sudo bash setup-deployment-users.sh \\
    --user alice --password pass1 --deployer \\
    --user bob --pubkey /tmp/bob_key.pub \\
    --user charlie --password pass3

EOF
}

# Main logic
main() {
    local init_dirs=false
    local users=()
    local current_user=""
    local current_password=""
    local current_pubkey=""
    local current_deployer=false

    # Parse arguments
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --init-directories)
                init_dirs=true
                shift
                ;;
            --user)
                # Save previous user if exists
                if [[ -n "$current_user" ]]; then
                    users+=("$current_user|$current_password|$current_pubkey|$current_deployer")
                fi
                current_user="$2"
                current_password=""
                current_pubkey=""
                current_deployer=false
                shift 2
                ;;
            --password)
                current_password="$2"
                shift 2
                ;;
            --pubkey)
                current_pubkey="$2"
                shift 2
                ;;
            --deployer)
                current_deployer=true
                shift
                ;;
            --help|-h)
                print_usage
                exit 0
                ;;
            *)
                log_error "Unknown option: $1"
                print_usage
                exit 1
                ;;
        esac
    done

    # Save last user if exists
    if [[ -n "$current_user" ]]; then
        users+=("$current_user|$current_password|$current_pubkey|$current_deployer")
    fi

    # Ensure groups exist
    ensure_groups

    # Initialize directories if requested
    if [[ "$init_dirs" == true ]]; then
        init_directories
        create_sudoers_file
    fi

    # Create users
    if [[ ${#users[@]} -gt 0 ]]; then
        for user_spec in "${users[@]}"; do
            IFS='|' read -r username password pubkey is_deployer <<< "$user_spec"
            create_user "$username" "$password" "$pubkey" "$is_deployer"
        done
    fi

    # Show summary if nothing was done
    if [[ "$init_dirs" == false && ${#users[@]} -eq 0 ]]; then
        log_warn "No actions specified. Use --init-directories or --user to perform actions."
        print_usage
        exit 1
    fi

    log_info "All operations completed successfully"
}

main "$@"
